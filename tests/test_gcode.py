def test_printer_metadata_comes_from_the_config_and_print_metadata_is_uncompressed():
    """PrusaSlicer pone el modelo de impresora y la boquilla solo en la configuración del final; la impresora los lee del
    bloque de la impresora. Como PrusaSlicer, solo los metadatos del laminador van con Deflate."""
    from tools.mesh import gcode as G

    text = ("; generated by PrusaSlicer 2.8.1\nM83\nG1 X1 Y1 Z0.2 E1\n; estimated printing time (normal mode) = 1m\n\n"
            "; prusaslicer_config = begin\n; printer_model = MK4S\n; nozzle_diameter = 0.4\n; filament_type = PETG\n"
            + "".join(f"; opcion_{k} = valor de prueba {k}\n" for k in range(200)) + "; prusaslicer_config = end\n").encode()
    doc = G.split_gcode(text)
    assert dict(doc.printer_meta) == {"printer_model": "MK4S", "nozzle_diameter": "0.4", "filament_type": "PETG"}
    doc.print_meta += [(f"clave_{k}", "x" * 40) for k in range(50)]  # comprimible: aun así va sin comprimir
    data = G.write_bgcode(doc)
    pos, kinds = 10, {}
    while pos < len(data):
        kind, compression, size = struct.unpack("<HHI", data[pos:pos + 8])
        stored = struct.unpack("<I", data[pos + 8:pos + 12])[0] if compression else size
        kinds.setdefault(kind, compression)
        pos += 8 + (4 if compression else 0) + (6 if kind == G.THUMBNAIL else 2) + stored + 4
    assert kinds[G.PRINT_META] == G.NONE and kinds[G.PRINTER_META] == G.NONE and kinds[G.FILE_META] == G.NONE
    assert kinds[G.SLICER_META] == G.DEFLATE


def test_split_and_encode_never_lose_commands():
    from tools.mesh import gcode as G

    # Configuración sin «end» y miniatura sin «end»: el resto sigue siendo G-code.
    for marker in (b"; prusaslicer_config = begin\n", b"; thumbnail begin 16x16 100\n"):
        text = b"G28\n" + marker + b"G1 X10 Y10 E1\nM84\n"
        doc = G.split_gcode(text)
        assert b"G1 X10 Y10 E1" in doc.gcode and b"M84" in doc.gcode, marker
    # Una línea de 70 KB sale entera; los bytes 0xFF no se confunden con señales de MeatPack.
    long = b"M117 " + b"A" * 70_000
    raw = b"G28\n" + long + b"\nM117 \xff\xffZ\nM84\n"
    back = G.read_bgcode(G.write_bgcode(G.split_gcode(raw))).gcode
    lines = bytes(back).split(b"\n")
    assert long in lines and b"M84" in lines
    assert any(line.startswith(b"M117 ") and line.endswith(b"Z") and len(line) > 6 for line in lines if line != long)
    # Miniatura con medidas imposibles: no es una miniatura (y no rompe la escritura).
    odd = b"; thumbnail begin 99999x16 4\n; AAAA\n; thumbnail end\nG1 X1 Y1 E1\n"
    assert not G.split_gcode(odd).thumbnails
    G.write_bgcode(G.split_gcode(odd))


