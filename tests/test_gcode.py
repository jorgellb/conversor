def test_meatpack_and_heatshrink_known_vectors():
    """Vectores hechos a mano según la especificación (no solo ida y vuelta con nuestro propio codificador); son los mismos
    que comprueba el lector del navegador (packages/client-tools/test/gcode3d.test.ts)."""
    from tools.mesh import gcode as G

    on = bytes([0xFF, 0xFF, 0xFB])
    nib = lambda a, b: a | (b << 4)  # noqa: E731
    assert G.meatpack_decode(on + bytes([nib(0xD, 1), nib(0xB, 0xE), nib(1, 0), nib(0xC, 0xC)])) == b"G1 X10\n"
    assert G.meatpack_decode(on + bytes([nib(0xD, 1), nib(0xB, 0xF), 0x59, nib(5, 0xC)])) == b"G1 Y5\n"
    nospace = on + bytes([0xFF, 0xFF, 0xF7, nib(0xD, 1), nib(0xE, 2), nib(0xB, 3), nib(0xC, 0xC)])
    assert G.meatpack_decode(nospace) == b"G1 X2 E3\n"
    bits = "1" + "01000001" + "1" + "01000010" + "0" + "00000001" + "0011"
    data = int(bits.ljust(-(-len(bits) // 8) * 8, "0"), 2).to_bytes(-(-len(bits) // 8), "big")
    assert G.heatshrink_decode(data, 8, 4, 6) == b"ABABAB"
