def _block(kind: int, params: bytes, raw: bytes, deflate: bool = True) -> bytes:
    import zlib

    stored = zlib.compress(raw, 9) if deflate else raw
    head = struct.pack("<HHI", kind, 1 if deflate else 0, len(raw)) + (struct.pack("<I", len(stored)) if deflate else b"")
    body = head + params + stored
    return body + struct.pack("<I", zlib.crc32(body))


def test_bgcode_metadata_and_thumbnail_bombs_are_refused(make_ctx, tmp_path):
    """Unos KB que se descomprimen en GB de metadatos o de miniaturas acaban en LIMIT_EXCEEDED, no en el trabajador muerto."""
    from tools.mesh import gcode as G

    head = G.MAGIC + struct.pack("<IH", 1, 1)
    meta = head + _block(G.SLICER_META, struct.pack("<H", 0), b"a=b\n" * (2 * 1024 * 1024))  # 8 MB en unos KB
    with pytest.raises(ToolError) as err:
        G.read_bgcode(meta)
    assert err.value.detail == "bgcode_metadata"
    thumbs = head + b"".join(_block(G.THUMBNAIL, struct.pack("<HHH", 0, 16, 16), b"\0" * 1024) for _ in range(G.MAX_THUMBS + 1))
    with pytest.raises(ToolError) as err:
        G.read_bgcode(thumbs)
    assert err.value.detail == "bgcode_thumbnails"
    # Por la herramienta, en el proceso hijo: el mismo error, limpio.
    path = tmp_path / "bomba.bgcode"
    path.write_bytes(meta)
    with pytest.raises(ToolError) as err:
        run("bgcode-a-gcode", make_ctx("bgcode-a-gcode", [path]))
    assert err.value.detail == "bgcode_metadata"


