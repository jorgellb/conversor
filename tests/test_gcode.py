def _png(w: int = 16, h: int = 16) -> bytes:
    from PIL import Image

    buf = io.BytesIO()
    Image.new("RGB", (w, h), (200, 30, 30)).save(buf, "PNG")
    return buf.getvalue()


def _gcode(layers: int = 5, thumbs: bool = True) -> bytes:
    lines = ["; generated by PrusaSlicer 2.8.1 on 2026-11-21 at 10:00:00 UTC", "", "; printer_model = MK4S", "; filament_type = PLA",
             "; nozzle_diameter = 0.4", "; layer_height = 0.2", ""]
    if thumbs:
        b64 = base64.b64encode(_png(220, 124)).decode()
        lines += [";", f"; thumbnail begin 220x124 {len(b64)}"] + [f"; {b64[i:i + 78]}" for i in range(0, len(b64), 78)] + ["; thumbnail end", ";"]
    lines += ["M83", "M104 S215", "M140 S60", "M190 S60", "M109 S215", "G28", "G92 E0", "M862.3 P \"MK4S\""]
    for k in range(layers):
        z = 0.2 * (k + 1)
        lines += [f";LAYER_CHANGE", f";Z:{z:.1f}", f"G1 Z{z:.1f} F720", "G1 X10 Y10 F9000", "G1 X60 Y10 E2.5", "G1 X60 Y40 E1.5",
                  "G1 X10 Y40 E2.5", "G1 X10 Y10 E1.5", "G1 E-0.8 F2100"]
    lines += ["M107", "; filament used [mm] = 1234.56", "; filament used [g] = 3.68", "; estimated printing time (normal mode) = 1h 2m 3s",
              "", "; prusaslicer_config = begin", "; layer_height = 0.2", "; post_process = ", "; prusaslicer_config = end"]
    return ("\n".join(lines) + "\n").encode()


def _cmds(data: bytes) -> list[str]:
    return [l.strip() for l in data.decode().splitlines() if l.strip() and not l.lstrip().startswith(";")]


def test_heatshrink_and_meatpack_roundtrip():
    from tools.mesh import gcode as G

    text = _gcode(40) * 3
    for window in (11, 12):
        packed = G.heatshrink_encode(text, window, 4)
        assert len(packed) < len(text) // 2 and G.heatshrink_decode(packed, window, 4, len(text)) == text
    encoded = G.meatpack_encode(text)
    assert len(encoded) < len(text) and _cmds(G.meatpack_decode(encoded)) == _cmds(text)
    assert b"; filament used [g] = 3.68" in G.meatpack_decode(encoded)  # los comentarios se conservan


def test_meatpack_no_space_mode_restores_spaces():
    from tools.mesh import gcode as G

    # «G1 X1.5 E2» empaquetado en el modo sin espacios (FF FF F7): la E va con el nibble del espacio.
    chars = b"G1X1.5E2\n"
    nib = {c: k for k, c in enumerate(b"0123456789.E\nGX")}
    body = bytearray(b"\xff\xff\xfb\xff\xff\xf7")
    data = chars + (b"\n" if len(chars) % 2 else b"")
    for i in range(0, len(data), 2):
        body.append(nib[data[i]] | (nib[data[i + 1]] << 4))
    assert G.meatpack_decode(bytes(body)) == b"G1 X1.5 E2\n"


def test_gcode_to_bgcode_and_back(make_ctx, tmp_path):
    from tools.mesh import gcode as G

    src = tmp_path / "pieza.gcode"
    src.write_bytes(_gcode())
    out = run("gcode-a-bgcode", make_ctx("gcode-a-bgcode", [src]))
    bg = Path(out[0]["path"])
    data = bg.read_bytes()
    assert data[:4] == b"GCDE" and struct.unpack("<IH", data[4:10]) == (1, 1) and "1 miniaturas" in out[0]["note"]
    doc = G.read_bgcode(data)
    assert dict(doc.printer_meta)["printer_model"] == "MK4S" and dict(doc.file_meta)["Producer"] == "PrusaSlicer 2.8.1"
    assert doc.thumbnails[0][:3] == ("png", 220, 124) and dict(doc.slicer_meta)["post_process"] == ""
    assert "estimated printing time (normal mode)" in dict(doc.print_meta)
    back = run("bgcode-a-gcode", make_ctx("bgcode-a-gcode", [bg]))
    text = Path(back[0]["path"]).read_bytes()
    assert _cmds(text) == _cmds(_gcode()) and text.startswith(b"; generated by PrusaSlicer 2.8.1")
    assert b"; thumbnail begin 220x124" in text and b"; prusaslicer_config = begin" in text


def test_bgcode_crc_and_truncation_are_detected(tmp_path):
    from tools.mesh import gcode as G

    data = bytearray(G.write_bgcode(G.split_gcode(_gcode())))
    data[200] ^= 0xFF
    with pytest.raises(ToolError) as err:
        G.read_bgcode(bytes(data))
    assert err.value.detail == "bgcode_crc"
    with pytest.raises(ToolError):
        G.read_bgcode(bytes(data[:150]))
    with pytest.raises(ToolError):
        G.read_bgcode(b"GCDE" + struct.pack("<IH", 2, 1))


def test_analyse_gcode(make_ctx, tmp_path):
    src = tmp_path / "pieza.gcode"
    src.write_bytes(_gcode(5))
    out = run("analizar-gcode", make_ctx("analizar-gcode", [src], {"formato": "json"}))
    data = json.loads(Path(out[0]["path"]).read_text())
    assert data["laminador"] == "PrusaSlicer 2.8.1" and data["tiempo_s"] == 3723 and data["capas"] == 5
    assert data["altura_maxima_mm"] == 1.0 and data["temperaturas_boquilla"] == [215] and data["temperaturas_cama"] == [60]
    assert data["extrusion_mm"] == 40.0 and data["filamento_g_comentario"] == 3.68
    assert data["caja_mm"] == {"x": [10.0, 60.0], "y": [10.0, 40.0], "z": [0.2, 1.0]}
    assert "1 h 2 min" in out[0]["note"]


def test_gcode_image_png_and_svg(make_ctx, tmp_path):
    from PIL import Image

    src = tmp_path / "pieza.gcode"
    src.write_bytes(_gcode(5))
    out = run("gcode-a-imagen", make_ctx("gcode-a-imagen", [src], {"capa": 2, "tamano": 400}))
    with Image.open(out[0]["path"]) as img:
        assert img.size == (400, 400) and len(img.getcolors(10000)) > 1
    assert "Capa 2 de 5" in out[0]["note"]
    out = run("gcode-a-imagen", make_ctx("gcode-a-imagen", [src], {"formato": "svg"}))
    assert Path(out[0]["path"]).read_text().count("<path") == 5
    with pytest.raises(ToolError):
        run("gcode-a-imagen", make_ctx("gcode-a-imagen", [src], {"capa": 9}))


def _qoi(w: int, h: int, rgba: tuple[int, int, int, int]) -> bytes:
    body = bytearray()
    for _ in range(w * h):
        body += bytes([0xFF, *rgba])
    return b"qoif" + struct.pack(">II", w, h) + bytes([4, 0]) + bytes(body) + b"\x00" * 7 + b"\x01"


def test_thumbnails_png_and_qoi(make_ctx, tmp_path):
    from PIL import Image

    from tools.mesh import gcode as G

    src = tmp_path / "pieza.gcode"
    src.write_bytes(_gcode())
    out = run("extraer-miniatura-gcode", make_ctx("extraer-miniatura-gcode", [src]))
    assert out[0]["name"] == "pieza-220x124.png"
    doc = G.split_gcode(_gcode(thumbs=False))
    doc.thumbnails = [("qoi", 3, 2, _qoi(3, 2, (10, 200, 30, 255)))]
    bg = tmp_path / "con-qoi.bgcode"
    bg.write_bytes(G.write_bgcode(doc))
    out = run("extraer-miniatura-gcode", make_ctx("extraer-miniatura-gcode", [bg]))
    with Image.open(out[0]["path"]) as img:
        assert img.size == (3, 2) and img.getpixel((1, 1))[:3] == (10, 200, 30)
    plain = tmp_path / "sin.gcode"
    plain.write_bytes(_gcode(thumbs=False))
    with pytest.raises(ToolError):
        run("extraer-miniatura-gcode", make_ctx("extraer-miniatura-gcode", [plain]))


def test_bambu_gcode_3mf(make_ctx, tmp_path):
    path = tmp_path / "proyecto.gcode.3mf"
    with zipfile.ZipFile(path, "w") as zf:
        zf.writestr("[Content_Types].xml", "<Types/>")
        zf.writestr("Metadata/plate_1.gcode", _gcode(2).decode())
        zf.writestr("Metadata/plate_1.png", _png())
        zf.writestr("Metadata/plate_2.gcode", _gcode(3).decode())
    from core.filetype import detect

    assert detect(path, ".3mf").ext == "3mf"
    out = run("extraer-gcode-3mf", make_ctx("extraer-gcode-3mf", [path]))
    archive = next(o for o in out if o["name"].endswith(".zip"))
    with zipfile.ZipFile(archive["path"]) as zf:
        assert sorted(zf.namelist()) == ["proyecto-placa-1.gcode", "proyecto-placa-1.png", "proyecto-placa-2.gcode"]
    out = run("extraer-gcode-3mf", make_ctx("extraer-gcode-3mf", [path], {"placa": 2}))
    assert out[0]["name"] == "proyecto-placa-2.gcode"


