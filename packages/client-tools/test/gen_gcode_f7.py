"""Genera fixtures/pieza.gcode y fixtures/pieza.bgcode para el visor de G-code (D-257).

El G-code imita a PrusaSlicer (`;LAYER_CHANGE`, `;TYPE:`, tiempo estimado, extrusión relativa con M83) e incluye un arco
G2, desplazamientos con salto en Z y retracciones. El bgcode sale del codificador propio del servidor (D-255):
Heatshrink 12,4 y MeatPack con comentarios. Uso: `.venv/bin/python packages/client-tools/test/gen_gcode_f7.py`.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
sys.path[:0] = [str(ROOT / "packages/tools"), str(ROOT / "packages/core")]

from tools.mesh.gcode import split_gcode, write_bgcode  # noqa: E402

lines = ["; generated by PrusaSlicer 2.8.1+linux-x64-GTK3 on 2026-11-01 at 10:00:00 UTC", "M83", "G21", "G90", "G28",
         "M104 S215", "M140 S60"]
for layer in range(10):
    z = round(0.2 * (layer + 1), 2)
    lines += [";LAYER_CHANGE", f";Z:{z}", f";HEIGHT:0.2", "G1 E-0.8 F2100", f"G1 Z{z + 0.4:.2f} F720", "G1 X100 Y100 F9000",
              f"G1 Z{z:.2f} F720", "G1 E0.8 F2100", ";TYPE:External perimeter", "G1 F1800"]
    lines += ["G1 X120 Y100 E0.665", "G1 X120 Y120 E0.665", "G1 X100 Y120 E0.665", "G1 X100 Y100 E0.665"]
    lines += [";TYPE:Solid infill" if layer in (0, 9) else ";TYPE:Internal infill", "G1 X102 Y102 F9000", "G1 X118 Y118 E0.75 F3000"]
    if layer == 5:
        lines += [";TYPE:Perimeter", "G1 X130 Y110 F9000", "G2 X130 Y110 I-5 J0 E1.0 F1200"]  # círculo entero de radio 5
lines += ["M107", "; filament used [mm] = 99.80", "; estimated printing time (normal mode) = 3m 12s", "M84"]
text = ("\n".join(lines) + "\n").encode()
out = Path(__file__).parent / "fixtures"
(out / "pieza.gcode").write_bytes(text)
(out / "pieza.bgcode").write_bytes(write_bgcode(split_gcode(text)))
print("ok", len(text))
