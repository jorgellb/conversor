def _t(ctx: ToolContext) -> dict:
    return TEXTS.get(ctx.locale, TEXTS["es"])


def _size(n: int) -> str:
    return f"{n / 1024 / 1024:.1f} MB" if n >= 1024 * 1024 else f"{max(1, n // 1024)} KB"


def _ext(inp) -> str:
    return (inp.ext or Path(inp.name).suffix.lstrip(".")).lower()


def load_text(inp) -> tuple[bytes, G.Bgcode | None]:
    """El G-code de texto de una entrada .gcode o .bgcode (y el documento binario si lo era)."""
    data = inp.path.read_bytes()
    if data[:4] == G.MAGIC:
        doc = G.read_bgcode(data)
        return G.join_gcode(doc), doc
    if b"\x00" in data[:4096]:
        raise ToolError(ErrorCode.UNSUPPORTED_FORMAT, "gcode_binary")
    return data, None


# ——— Conversiones ———

def run_to_bgcode(ctx: ToolContext) -> list[dict]:
    t = _t(ctx)
    outputs = []
    for n, inp in enumerate(ctx.inputs):
        text = inp.path.read_bytes()
        doc = G.split_gcode(text)
        if not doc.gcode.strip():
            raise ToolError(ErrorCode.INVALID_OPTIONS, "gcode_empty")
        data = G.write_bgcode(doc, compress=ctx.options.comprimir,
                              progress=lambda f, n=n: ctx.report((n + f) / len(ctx.inputs), None))
        name = derived_name(inp.name, "", "bgcode")
        dst = ctx.output(name)
        dst.write_bytes(data)
        outputs.append({"path": str(dst), "name": name, "note": t["to_bgcode"].format(
            before=_size(len(text)), after=_size(len(data)), pct=max(0, round(100 * (1 - len(data) / max(1, len(text))))),
            thumbs=len(doc.thumbnails))})
    return with_batch_zip(ctx, outputs, "gcode-binario.zip")


def run_to_gcode(ctx: ToolContext) -> list[dict]:
    t = _t(ctx)
    outputs = []
    for n, inp in enumerate(ctx.inputs):
        ctx.report(n / len(ctx.inputs), None)
        doc = G.read_bgcode(inp.path.read_bytes())
        name = derived_name(inp.name, "", "gcode")
        dst = ctx.output(name)
        dst.write_bytes(G.join_gcode(doc))
        producer = dict(doc.file_meta).get("Producer") or ("un laminador" if ctx.locale != "en" else "a slicer")
        outputs.append({"path": str(dst), "name": name, "note": t["to_gcode"].format(producer=producer, thumbs=len(doc.thumbnails))})
    return with_batch_zip(ctx, outputs, "gcode.zip")


# ——— Análisis ———

MOVE = re.compile(r"^G[0123](?:\s|$)")
WORD = re.compile(r"([XYZEF])\s*(-?\d*\.?\d+)")
TIME_PATTERNS = [
    re.compile(r"^;\s*estimated printing time(?: \(normal mode\))?\s*=\s*(.+)$", re.I),  # PrusaSlicer, Orca, Bambu
    re.compile(r"^;\s*TIME:\s*(\d+)\s*$"),  # Cura (segundos)
    re.compile(r"^;\s*Build time:\s*(.+)$", re.I),  # Simplify3D
    re.compile(r"^;\s*model printing time:\s*([^;]+)", re.I),  # Bambu Studio
]
SLICER = re.compile(r"^;\s*(?:generated by|Generated with|FLAVOR:|G-Code generated by)\s*(.+?)(?: on .*)?$", re.I)


def _duration(text: str) -> int | None:
    text = text.strip()
    if text.isdigit():
        return int(text)
    total, found = 0, False
    for value, unit in re.findall(r"(\d+)\s*([dhms])", text):
        total += int(value) * {"d": 86400, "h": 3600, "m": 60, "s": 1}[unit]
        found = True
    return total if found else None


def _fmt_duration(seconds: int | None, es: bool) -> str:
    if seconds is None:
        return "desconocido" if es else "unknown"
    h, rest = divmod(int(seconds), 3600)
    m, s = divmod(rest, 60)
    return f"{h} h {m} min" if h else f"{m} min {s} s"


def analyse(text: bytes, max_layers_kept: int = 0) -> dict:
    """Recorrido del G-code: tiempo, filamento y laminador de los comentarios; capas, alturas, caja y longitud de
    extrusión de los movimientos (E absoluto o relativo, M82/M83 y G92), y temperaturas de M104/M109 y M140/M190."""
    relative_e = False
    x = y = z = e = 0.0
    extruded = 0.0
    layers: dict[float, int] = {}
    box = [math.inf, math.inf, math.inf, -math.inf, -math.inf, -math.inf]
    temps_nozzle, temps_bed = set(), set()
    info: dict = {"laminador": None, "tiempo_s": None, "filamento_m_comentario": None, "filamento_g_comentario": None}
    moves = 0
    for raw in text.decode("utf-8", "replace").splitlines():
        line = raw.strip()
        if not line:
            continue
        if line.startswith(";"):
            if info["laminador"] is None and (m := SLICER.match(line)):
                info["laminador"] = m.group(1).strip()[:80]
            if info["tiempo_s"] is None:
                for pattern in TIME_PATTERNS:
                    if m := pattern.match(line):
                        info["tiempo_s"] = _duration(m.group(1))
                        break
            low = line.lower()
            if "filament used [mm]" in low and info["filamento_m_comentario"] is None:
                try:
                    info["filamento_m_comentario"] = round(sum(float(v) for v in re.findall(r"[\d.]+", line.split("=", 1)[1])) / 1000, 3)
                except (IndexError, ValueError):
                    pass
            if ("filament used [g]" in low or "total filament used [g]" in low) and info["filamento_g_comentario"] is None:
                try:
                    info["filamento_g_comentario"] = round(sum(float(v) for v in re.findall(r"[\d.]+", line.split("=", 1)[1])), 2)
                except (IndexError, ValueError):
                    pass
            if low.startswith(";filament used:"):  # Cura: «;Filament used: 1.234m»
                try:
                    info["filamento_m_comentario"] = float(re.findall(r"[\d.]+", low)[0])
                except (IndexError, ValueError):
                    pass
            continue
        code = line.split(";", 1)[0].strip().upper()
        if code.startswith("M82"):
            relative_e = False
        elif code.startswith("M83"):
            relative_e = True
        elif code.startswith(("M104", "M109")) and (m := re.search(r"S(\d+)", code)) and int(m.group(1)) > 0:
            temps_nozzle.add(int(m.group(1)))
        elif code.startswith(("M140", "M190")) and (m := re.search(r"S(\d+)", code)) and int(m.group(1)) > 0:
            temps_bed.add(int(m.group(1)))
        elif code.startswith("G92"):
            for k, v in WORD.findall(code):
                if k == "E":
                    e = float(v)
        elif MOVE.match(code):
            moves += 1
            words = dict(WORD.findall(code))
            nx, ny, nz = float(words.get("X", x)), float(words.get("Y", y)), float(words.get("Z", z))
            de = 0.0
            if "E" in words:
                ne = float(words["E"])
                de = ne if relative_e else ne - e
                e = e + ne if relative_e else ne
            if de > 1e-6 and (nx != x or ny != y):
                extruded += de
                layers[round(nz, 3)] = layers.get(round(nz, 3), 0) + 1
                box = [min(box[0], x, nx), min(box[1], y, ny), min(box[2], nz), max(box[3], x, nx), max(box[4], y, ny), max(box[5], nz)]
            x, y, z = nx, ny, nz
    heights = sorted(layers)
    result = {
        **info,
        "capas": len(heights), "altura_maxima_mm": heights[-1] if heights else None,
        "altura_primera_capa_mm": heights[0] if heights else None,
        "caja_mm": None if not heights else {"x": [round(box[0], 2), round(box[3], 2)], "y": [round(box[1], 2), round(box[4], 2)],
                                            "z": [round(box[2], 2), round(box[5], 2)]},
        "extrusion_mm": round(extruded, 1), "temperaturas_boquilla": sorted(temps_nozzle), "temperaturas_cama": sorted(temps_bed),
        "movimientos": moves,
    }
    if max_layers_kept:
        result["_layers"] = heights
    return result


def run_analyse(ctx: ToolContext) -> list[dict]:
    t = _t(ctx)
    es = ctx.locale != "en"
    outputs = []
    for n, inp in enumerate(ctx.inputs):
        ctx.report(n / len(ctx.inputs), None)
        text, _doc = load_text(inp)
        data = analyse(text)
        metres = data["filamento_m_comentario"] or data["extrusion_mm"] / 1000
        grams = f" ({data['filamento_g_comentario']:.1f} g)" if data["filamento_g_comentario"] else ""
        summary = [t["time"].format(t=_fmt_duration(data["tiempo_s"], es)), t["filament"].format(m=metres, g=grams), t["layers"].format(n=data["capas"])]
        stem = Path(inp.name).stem.replace(".gcode", "")
        if ctx.options.formato == "json":
            body = json.dumps(data, ensure_ascii=False, indent=2) + "\n"
        else:
            box = data["caja_mm"]
            lines = [("Análisis del G-code" if es else "G-code analysis"), "",
                     f"{'Laminador' if es else 'Slicer'}: {data['laminador'] or '—'}",
                     f"{'Tiempo estimado' if es else 'Estimated time'}: {_fmt_duration(data['tiempo_s'], es)}",
                     f"{'Filamento' if es else 'Filament'}: {metres:.2f} m{grams}",
                     f"{'Capas' if es else 'Layers'}: {data['capas']} ({'primera' if es else 'first'} {data['altura_primera_capa_mm']} mm, "
                     f"{'altura' if es else 'height'} {data['altura_maxima_mm']} mm)",
                     f"{'Temperaturas de la boquilla' if es else 'Nozzle temperatures'}: {', '.join(map(str, data['temperaturas_boquilla'])) or '—'} °C",
                     f"{'Temperaturas de la cama' if es else 'Bed temperatures'}: {', '.join(map(str, data['temperaturas_cama'])) or '—'} °C"]
            if box:
                lines.append(f"{'Área impresa' if es else 'Printed area'}: X {box['x'][0]}–{box['x'][1]}, Y {box['y'][0]}–{box['y'][1]} mm")
            lines.append(f"{'Movimientos' if es else 'Moves'}: {data['movimientos']:,}".replace(",", "." if es else ","))
            body = "\n".join(lines) + "\n"
        name = f"{stem}-{'analisis' if es else 'analysis'}.{ctx.options.formato}"
        dst = ctx.output(name)
        dst.write_text(body, encoding="utf-8")
        outputs.append({"path": str(dst), "name": name, "note": " ".join(summary)})
    return with_batch_zip(ctx, outputs, "analisis-gcode.zip")


# ——— Imagen de las trayectorias ———

def run_image(ctx: ToolContext) -> list[dict]:
    """Trayectorias de extrusión de una capa (o de todas, coloreadas por altura) vistas desde arriba, en PNG o SVG."""
    o = ctx.options
    t = _t(ctx)
    outputs = []
    for n, inp in enumerate(ctx.inputs):
        ctx.report(n / len(ctx.inputs), None)
        text, _doc = load_text(inp)
        segments, heights = _segments(text)
        if not segments:
            raise ToolError(ErrorCode.INVALID_OPTIONS, "gcode_no_moves")
        if o.capa > 0:
            if o.capa > len(heights):
                raise ToolError(ErrorCode.INVALID_OPTIONS, "gcode_layer")
            z = heights[o.capa - 1]
            segments = [s for s in segments if s[4] == z]
            note = t["layer"].format(n=o.capa, total=len(heights), z=z)
        else:
            note = t["all"]
        stem = Path(inp.name).stem.replace(".gcode", "")
        name = f"{stem}-{'capa' if ctx.locale != 'en' else 'layer'}-{o.capa}.{o.formato}" if o.capa else f"{stem}.{o.formato}"
        dst = ctx.output(name)
        if o.formato == "svg":
            dst.write_text(_svg(segments, heights), encoding="utf-8")
        else:
            dst.write_bytes(_png(segments, heights, o.tamano))
        outputs.append({"path": str(dst), "name": name, "note": note})
    return with_batch_zip(ctx, outputs, "trayectorias.zip")


def _segments(text: bytes, limit: int = 3_000_000) -> tuple[list[tuple[float, float, float, float, float]], list[float]]:
    relative_e = False
    x = y = z = e = 0.0
    out = []
    for raw in text.decode("utf-8", "replace").splitlines():
        code = raw.split(";", 1)[0].strip().upper()
        if not code:
            continue
        if code.startswith("M83"):
            relative_e = True
        elif code.startswith("M82"):
            relative_e = False
        elif code.startswith("G92"):
            for k, v in WORD.findall(code):
                if k == "E":
                    e = float(v)
        elif MOVE.match(code):
            words = dict(WORD.findall(code))
            nx, ny, nz = float(words.get("X", x)), float(words.get("Y", y)), float(words.get("Z", z))
            de = 0.0
            if "E" in words:
                ne = float(words["E"])
                de = ne if relative_e else ne - e
                e = e + ne if relative_e else ne
            if de > 1e-6 and (nx != x or ny != y):
                out.append((x, y, nx, ny, round(nz, 3)))
                if len(out) > limit:
                    raise ToolError(ErrorCode.LIMIT_EXCEEDED, "gcode_too_many_moves")
            x, y, z = nx, ny, nz
    return out, sorted({s[4] for s in out})


def _colour(z: float, heights: list[float]) -> tuple[int, int, int]:
    if len(heights) < 2:
        return (230, 90, 20)
    f = (z - heights[0]) / (heights[-1] - heights[0])
    return (int(40 + 200 * f), int(90 + 60 * (1 - abs(0.5 - f) * 2)), int(220 - 200 * f))


def _png(segments, heights, size: int) -> bytes:
    from PIL import Image, ImageDraw

    xs = [v for s in segments for v in (s[0], s[2])]
    ys = [v for s in segments for v in (s[1], s[3])]
    lo_x, hi_x, lo_y, hi_y = min(xs), max(xs), min(ys), max(ys)
    span = max(hi_x - lo_x, hi_y - lo_y, 1e-6)
    margin = size * 0.04
    scale = (size - 2 * margin) / span
    img = Image.new("RGB", (size, size), (255, 255, 255))
    draw = ImageDraw.Draw(img)
    for x0, y0, x1, y1, z in segments:
        p0 = (margin + (x0 - lo_x) * scale, size - margin - (y0 - lo_y) * scale)
        p1 = (margin + (x1 - lo_x) * scale, size - margin - (y1 - lo_y) * scale)
        draw.line([p0, p1], fill=_colour(z, heights), width=max(1, size // 600))
    buf = io.BytesIO()
    img.save(buf, "PNG", optimize=True)
    return buf.getvalue()


def _svg(segments, heights) -> str:
    xs = [v for s in segments for v in (s[0], s[2])]
    ys = [v for s in segments for v in (s[1], s[3])]
    lo_x, hi_x, lo_y, hi_y = min(xs), max(xs), min(ys), max(ys)
    w, h = max(hi_x - lo_x, 1e-3), max(hi_y - lo_y, 1e-3)
    by_z: dict[float, list[str]] = {}
    for x0, y0, x1, y1, z in segments[:400_000]:
        by_z.setdefault(z, []).append(f"M{x0 - lo_x:.2f} {hi_y - y0:.2f}L{x1 - lo_x:.2f} {hi_y - y1:.2f}")
    paths = "".join(f'<path stroke="rgb{_colour(z, heights)}" d="{"".join(d)}"/>' for z, d in sorted(by_z.items()))
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{w:.2f}mm" height="{h:.2f}mm" viewBox="0 0 {w:.2f} {h:.2f}">'
            f'<g fill="none" stroke-width="0.4" stroke-linecap="round">{paths}</g></svg>\n')


# ——— Miniaturas ———

def thumbnails_of(inp) -> list[tuple[str, int, int, bytes]]:
    data = inp.path.read_bytes()
    if data[:4] == G.MAGIC:
        return G.read_bgcode(data).thumbnails
    return G.split_gcode(data).thumbnails


def _as_image(fmt: str, data: bytes) -> tuple[str, bytes]:
    if fmt == "qoi":
        return "png", G.qoi_to_png(data)
    return ("jpg" if fmt == "jpg" else "png"), data


def run_thumbnails(ctx: ToolContext) -> list[dict]:
    t = _t(ctx)
    outputs = []
    for inp in ctx.inputs:
        stem = Path(inp.name).stem.replace(".gcode", "")
        thumbs = thumbnails_of(inp)
        if not thumbs:
            raise ToolError(ErrorCode.INVALID_OPTIONS, "gcode_no_thumbnails")
        for k, (fmt, w, h, data) in enumerate(sorted(thumbs, key=lambda x: -(x[1] * x[2]))):
            ext, image = _as_image(fmt, data)
            name = f"{stem}-{w}x{h}.{ext}"
            dst = ctx.output(name)
            dst.write_bytes(image)
            outputs.append({"path": str(dst), "name": dst.name, "note": t["thumbs"].format(n=len(thumbs)) if k == 0 else None})
    return with_batch_zip(ctx, outputs, "miniaturas.zip")


# ——— .gcode.3mf de Bambu Lab ———

def run_gcode_3mf(ctx: ToolContext) -> list[dict]:
    """El G-code de cada placa (Metadata/plate_N.gcode) y sus miniaturas (plate_N.png) de un .gcode.3mf."""
    t = _t(ctx)
    outputs = []
    for inp in ctx.inputs:
        check_zip(inp.path)
        with zipfile.ZipFile(inp.path) as zf:
            names = zf.namelist()
            plates = sorted({m.group(1) for n in names if (m := re.match(r"^Metadata/plate_(\d+)\.gcode$", n))}, key=int)
            if not plates:
                raise ToolError(ErrorCode.INVALID_OPTIONS, "gcode3mf_no_gcode")
            if ctx.options.placa:
                plates = [p for p in plates if int(p) == ctx.options.placa]
                if not plates:
                    raise ToolError(ErrorCode.INVALID_OPTIONS, "gcode3mf_plate")
            stem = Path(inp.name).name.split(".")[0]
            for plate in plates:
                for member, ext in ((f"Metadata/plate_{plate}.gcode", "gcode"), (f"Metadata/plate_{plate}.png", "png"),
                                    (f"Metadata/plate_{plate}_small.png", "png")):
                    if member not in names:
                        continue
                    suffix = "-mini" if member.endswith("_small.png") else ""
                    name = f"{stem}-placa-{plate}{suffix}.{ext}" if ctx.locale != "en" else f"{stem}-plate-{plate}{suffix}.{ext}"
                    dst = ctx.output(name)
                    with zf.open(member) as src, open(dst, "wb") as out:
                        out.write(src.read(1024 * 1024 * 1024))
                    outputs.append({"path": str(dst), "name": dst.name})
            if outputs:
                outputs[0]["note"] = t["plates"].format(n=len(plates))
    return with_batch_zip(ctx, outputs, "placas.zip")
